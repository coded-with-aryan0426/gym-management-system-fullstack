-- 2. Create MEMBERSHIPS table if not exists
DECLARE
  v_count NUMBER;
BEGIN
  SELECT count(*) INTO v_count FROM user_tables WHERE table_name = 'MEMBERSHIPS';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE '
      CREATE TABLE memberships (
        membership_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id NUMBER NOT NULL,
        gym_id NUMBER NOT NULL,
        package_id NUMBER,
        start_date DATE,
        end_date DATE,
        status VARCHAR2(20) DEFAULT ''ACTIVE'',
        payment_status VARCHAR2(20) DEFAULT ''PAID'',
        auto_renew NUMBER(1) DEFAULT 0,
        CONSTRAINT fk_mem_user FOREIGN KEY (user_id) REFERENCES users(user_id) ON DELETE CASCADE,
        CONSTRAINT fk_mem_gym FOREIGN KEY (gym_id) REFERENCES gyms(gym_id) ON DELETE CASCADE
      )';
  END IF;
END;
